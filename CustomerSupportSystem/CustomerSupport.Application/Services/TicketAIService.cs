using CustomerSupport.Application.Configurations;
using CustomerSupport.Application.DTOs.AI;
using CustomerSupport.Application.DTOs.Tickets;
using CustomerSupport.Application.Exceptions;
using CustomerSupport.Application.Interfaces.Services;
using CustomerSupport.Application.Prompts;
using Microsoft.Extensions.AI;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using System.Globalization;

namespace CustomerSupport.Application.Services
{
  // Coordinates AI ticket analysis, draft generation, and reviewed comment saving.
  public sealed class TicketAIService : ITicketAIService
  {
    // Existing application services used to retrieve and save ticket data.
    private readonly ITicketService _tickets;
    private readonly ITicketCategoryService _categories;
    private readonly IMasterDataService _masters;
    private readonly IKnowledgeBaseService _knowledgeBase;

    // Provides the selected OpenAI or Ollama IChatClient.
    private readonly IAIChatClientProvider _provider;

    // Records technical errors without exposing private ticket information.
    private readonly ILogger<TicketAIService> _logger;

    // Contains common AI settings such as timeout and output-token limit.
    private readonly AISettings _settings;

    // Receive all required services and configuration through Dependency Injection.
    public TicketAIService(
        ITicketService tickets,
        ITicketCategoryService categories,
        IMasterDataService masters,
        IKnowledgeBaseService knowledgeBase,
        IAIChatClientProvider provider,
        IOptions<AISettings> settings,
        ILogger<TicketAIService> logger)
    {
      _tickets = tickets;
      _categories = categories;
      _masters = masters;
      _knowledgeBase = knowledgeBase;
      _provider = provider;
      _settings = settings.Value;
      _logger = logger;
    }

    // Analyze a ticket and return strongly typed information generated by AI.
    public async Task<TicketStructuredAnalysisResponseDTO> AnalyzeAsync(
        int ticketId,
        CancellationToken cancellationToken = default)
    {
      // Reject invalid Ticket IDs before accessing the database.
      CheckTicketId(ticketId);

      // Retrieve the ticket using the existing access-controlled service.
      TicketDetailsResponseDTO ticket =
          await _tickets.GetByIdAsync(ticketId);

      // Retrieve active ticket categories from SQL Server.
      var categories =
          await _categories.GetAllAsync(activeOnly: true);

      // Retrieve ticket priorities and keep only active records.
      var allPriorities =
          await _masters.GetTicketPrioritiesAsync();

      var priorities = allPriorities
          .Where(x => x.IsActive)
          .ToList();

      // AI needs valid category and priority choices for its suggestions.
      if (!categories.Any() || !priorities.Any())
      {
        throw new ApplicationValidationException(
            ["Active categories and priorities are required."]);
      }

      // Prepare the ticket details and allowed category/priority names.
      string input = TicketAIContextBuilder.ForAnalysis(
          ticket,
          categories.Select(x => x.Name),
          priorities.Select(x => x.Name));

      // Ask the selected AI provider to return a TicketAnalysisDTO.
      ChatResponse<TicketAnalysisDTO> result =
          await AskStructuredAsync(input, cancellationToken);

      // Extract the typed result and reject an invalid AI response.
      if (!result.TryGetResult(out TicketAnalysisDTO? analysis) ||
          analysis is null)
      {
        throw new AIException(
            "AI returned invalid structured analysis.");
      }

      // Check that the AI returned valid required fields and sentiment.
      if (string.IsNullOrWhiteSpace(analysis.Problem) ||
          string.IsNullOrWhiteSpace(analysis.NextStep) ||
          analysis.ActionsTried is null ||
          analysis.ActionsTried.Any(string.IsNullOrWhiteSpace) ||
          !Enum.IsDefined(analysis.Sentiment))
      {
        throw new AIException(
            "AI returned incomplete analysis.");
      }

      // Find the suggested category in the active category records.
      // Ignore uppercase/lowercase differences when matching names.
      var category = analysis.SuggestedCategory is null
          ? null
          : categories.FirstOrDefault(x =>
              x.Name.Equals(
                  analysis.SuggestedCategory.Trim(),
                  StringComparison.OrdinalIgnoreCase));

      // Reject a category that does not exist in the active master data.
      if (analysis.SuggestedCategory is not null &&
          category is null)
      {
        throw new AIException(
            "Unsupported category suggested by AI.");
      }

      // Find the suggested priority in the active priority records.
      var priority = analysis.SuggestedPriority is null
          ? null
          : priorities.FirstOrDefault(x =>
              x.Name.Equals(
                  analysis.SuggestedPriority.Trim(),
                  StringComparison.OrdinalIgnoreCase));

      // Reject a priority that does not exist in the active master data.
      if (analysis.SuggestedPriority is not null &&
          priority is null)
      {
        throw new AIException(
            "Unsupported priority suggested by AI.");
      }

      // Verify that an AI-generated resolution date is a real yyyy-MM-dd date.
      if (analysis.ConfirmedResolutionDate is not null)
      {
        bool isValidDate = DateOnly.TryParseExact(
            analysis.ConfirmedResolutionDate,
            "yyyy-MM-dd",
            CultureInfo.InvariantCulture,
            DateTimeStyles.None,
            out _);

        if (!isValidDate)
        {
          throw new AIException(
              "AI returned an invalid resolution date.");
        }
      }

      // Return the AI analysis along with validated database IDs.
      // This method only generates suggestions; it does not update SQL Server.
      return new TicketStructuredAnalysisResponseDTO
      {
        TicketId = ticketId,
        Analysis = analysis,

        // Return the matching database IDs, if available.
        SuggestedCategoryId = category?.Id,
        SuggestedPriorityId = priority?.Id,

        // Return information about the provider and model used.
        Provider = _provider.ProviderName,
        Model = result.ModelId ?? string.Empty,
        ResponseId = result.ResponseId ?? string.Empty,

        // Return reported input, output, and total token usage.
        InputTokens = TokenCount(
              result.Usage?.InputTokenCount),

        OutputTokens = TokenCount(
              result.Usage?.OutputTokenCount),

        TotalTokens = TokenCount(
              result.Usage?.TotalTokenCount)
      };
    }

    // Generate a customer-facing reply without using internal ticket comments.
    public Task<TicketDraftResponseDTO> GenerateReplyDraftAsync(
        int ticketId,
        TicketDraftRequestDTO request,
        CancellationToken cancellationToken = default)
    {
      // false selects the customer reply prompt and public comments.
      return GenerateDraftAsync(
          ticketId,
          request,
          isInternal: false,
          cancellationToken: cancellationToken);
    }

    // Generate an internal support note using public and internal comments.
    public Task<TicketDraftResponseDTO> GenerateInternalNoteDraftAsync(
        int ticketId,
        TicketDraftRequestDTO request,
        CancellationToken cancellationToken = default)
    {
      // true selects the internal note prompt and includes internal comments.
      return GenerateDraftAsync(
          ticketId,
          request,
          isInternal: true,
          cancellationToken: cancellationToken);
    }

    // Common method used by customer reply and internal note generation.
    private async Task<TicketDraftResponseDTO> GenerateDraftAsync(
        int ticketId,
        TicketDraftRequestDTO request,
        bool isInternal,
        CancellationToken cancellationToken)
    {
      // Validate the Ticket ID and request object.
      CheckTicketId(ticketId);

      if (request is null)
      {
        throw new ApplicationValidationException(
            ["Draft request is required."]);
      }

      // Load the ticket through the existing Ticket Service.
      TicketDetailsResponseDTO ticket =
          await _tickets.GetByIdAsync(ticketId);

      // Knowledge Base content is optional.
      string? articleText = null;

      if (request.KnowledgeBaseArticleId.HasValue)
      {
        // Retrieve the selected Knowledge Base article.
        var article = await _knowledgeBase.GetByIdAsync(
            request.KnowledgeBaseArticleId.Value);

        // Accept only active, published articles applicable to the ticket.
        if (!article.IsActive ||
            !article.IsPublished ||
            (article.ProductId.HasValue &&
             article.ProductId.Value != ticket.ProductId))
        {
          throw new ApplicationValidationException(
              ["Knowledge Base article is not available for this ticket."]);
        }

        // Limit article content to avoid sending excessive text to AI.
        string content = article.Content.Length > 2500
            ? article.Content[..2500]
            : article.Content;

        // Include the article title and content as reference information.
        articleText =
            $"Title: {article.Title}\nContent: {content}";
      }

      // Prepare ticket context based on whether the draft is internal.
      // Customer replies exclude staff-only comments.
      string input = TicketAIContextBuilder.ForDraft(
          ticket,
          articleText,
          includeInternalComments: isInternal);

      // Select the appropriate predefined instructions for the AI model.
      string instructions = isInternal
          ? TicketAIPrompts.InternalNote
          : TicketAIPrompts.ReplyDraft;

      // Request a plain-text draft from the configured AI provider.
      ChatResponse response = await AskTextAsync(
          instructions,
          input,
          cancellationToken);

      // Extract the generated text and remove surrounding whitespace.
      string draft = response.Text?.Trim() ?? string.Empty;

      // Limit the draft length to fit the reviewed-save request DTO.
      // Internal drafts reserve extra space for an AI-assisted label.
      int maximumLength = isInternal ? 1800 : 1900;

      // Reject empty or excessively long AI-generated drafts.
      if (draft.Length == 0 || draft.Length > maximumLength)
      {
        throw new AIException(
            "AI returned an unusable draft.");
      }

      // Return the generated draft for staff review without saving it.
      return new TicketDraftResponseDTO
      {
        TicketId = ticketId,
        DraftText = draft,

        // Include the provider and model used for this request.
        Provider = _provider.ProviderName,
        Model = response.ModelId ?? string.Empty,
        ResponseId = response.ResponseId ?? string.Empty,

        // Include token usage when reported by the provider.
        InputTokens = TokenCount(
              response.Usage?.InputTokenCount),

        OutputTokens = TokenCount(
              response.Usage?.OutputTokenCount),

        TotalTokens = TokenCount(
              response.Usage?.TotalTokenCount)
      };
    }

    // Save a staff-reviewed AI draft as an internal or customer-visible comment.
    public Task<TicketCommentResponseDTO> SaveReviewedDraftAsync(
        int ticketId,
        SaveReviewedAIDraftRequestDTO request)
    {
      // Validate the Ticket ID and ensure reviewed text is provided.
      CheckTicketId(ticketId);

      if (request is null ||
          string.IsNullOrWhiteSpace(request.ApprovedText))
      {
        throw new ApplicationValidationException(
            ["Reviewed text is required."]);
      }

      // Read the final text approved by the Support Executive.
      string text = request.ApprovedText.Trim();

      // Add an AI-assisted label only to internal comments.
      // Customer-visible comments must not contain this internal label.
      if (request.IsInternal)
      {
        text = "[AI-assisted; reviewed by staff]\n" + text;
      }

      // Ensure the final comment fits the existing 2000-character limit.
      if (text.Length > 2000)
      {
        throw new ApplicationValidationException(
            ["Reviewed comment must fit within 2000 characters."]);
      }

      // Save using the existing Ticket Service and its permission checks.
      // IsInternal = true: Staff-only comment.
      // IsInternal = false: Customer-visible comment.
      return _tickets.AddCommentAsync(
          ticketId,
          new AddTicketCommentRequestDTO
          {
            Content = text,
            IsInternal = request.IsInternal
          });
    }

    // Generate strongly typed JSON using Microsoft.Extensions.AI.
    private async Task<ChatResponse<TicketAnalysisDTO>>
        AskStructuredAsync(
            string input,
            CancellationToken cancellationToken)
    {
      // Link the API cancellation token with our configured AI timeout.
      using CancellationTokenSource timeout =
          CancellationTokenSource.CreateLinkedTokenSource(
              cancellationToken);

      timeout.CancelAfter(
          TimeSpan.FromSeconds(_settings.TimeoutSeconds));

      try
      {
        // System message contains our rules.
        // User message contains the ticket information to analyze.
        var messages = new List<ChatMessage>
                {
                    new(ChatRole.System, TicketAIPrompts.Analysis),
                    new(ChatRole.User, input)
                };

        // Use the selected provider to generate a typed TicketAnalysisDTO.
        // The library creates a JSON Schema from the C# DTO.
        return await _provider.GetClient()
            .GetResponseAsync<TicketAnalysisDTO>(
                messages,
                new ChatOptions
                {
                  MaxOutputTokens = _settings.MaxOutputTokens
                },
                useJsonSchemaResponseFormat: true,
                cancellationToken: timeout.Token);
      }
      catch (OperationCanceledException)
          when (!cancellationToken.IsCancellationRequested)
      {
        // Convert an AI timeout into a common application exception.
        throw new AIException("AI request timed out.");
      }
      catch (Exception ex)
          when (ex is not AIException &&
                ex is not OperationCanceledException)
      {
        // Log the exception type without recording private ticket data.
        _logger.LogWarning(
            "AI analysis failed: {Type}",
            ex.GetType().Name);

        // Return a safe error rather than exposing provider details.
        throw new AIException(
            "AI analysis could not be completed.");
      }
    }

    // Generate a plain-text response using Microsoft.Extensions.AI.
    private async Task<ChatResponse> AskTextAsync(
        string instructions,
        string input,
        CancellationToken cancellationToken)
    {
      // Create a cancellation token with the configured timeout.
      using CancellationTokenSource timeout =
          CancellationTokenSource.CreateLinkedTokenSource(
              cancellationToken);

      timeout.CancelAfter(
          TimeSpan.FromSeconds(_settings.TimeoutSeconds));

      try
      {
        // Send application instructions separately from ticket data.
        var messages = new List<ChatMessage>
                {
                    new(ChatRole.System, instructions),
                    new(ChatRole.User, input)
                };

        // Generate plain text using the configured IChatClient.
        return await _provider.GetClient()
            .GetResponseAsync(
                messages,
                new ChatOptions
                {
                  MaxOutputTokens = _settings.MaxOutputTokens
                },
                timeout.Token);
      }
      catch (OperationCanceledException)
          when (!cancellationToken.IsCancellationRequested)
      {
        // Handle a request that exceeded the configured timeout.
        throw new AIException("AI request timed out.");
      }
      catch (Exception ex)
          when (ex is not AIException &&
                ex is not OperationCanceledException)
      {
        // Record only technical information about the failure.
        _logger.LogWarning(
            "AI draft failed: {Type}",
            ex.GetType().Name);

        // Return a common error for all AI providers.
        throw new AIException(
            "AI draft could not be generated.");
      }
    }

    // Check that the requested Ticket ID is greater than zero.
    private static void CheckTicketId(int ticketId)
    {
      if (ticketId <= 0)
      {
        throw new ApplicationValidationException(
            ["A valid Ticket ID is required."]);
      }
    }

    // Convert optional token usage into a safe integer value.
    private static int TokenCount(long? value)
    {
      // Use zero when usage is missing and prevent integer overflow.
      return (int)Math.Clamp(
          value ?? 0,
          0,
          int.MaxValue);
    }
  }
}
